"""Query executors: ``execute(query) -> ExecResult``.

Every stack gets the same interface. chDB (T11) and Cube SQL / JSON (T16) are
implemented here; DAX is reserved for T17.

The chDB executor enforces a per-cell *database scope* before execution
(T11 card, carried-forward requirement 1): a query that names a table in a
database outside the cell's allowed set is rejected statically and reported as
an ordinary execution error with ``error_class = "scope_violation"``, so the
harness sends it back to the model like any other error, and the report can
count it separately (decisions/2026-10-16-l1_5s-lineage-and-execution-scope.md).
"""

from __future__ import annotations

import hashlib
import asyncio
import json
import os
import re
import secrets
import threading
import time
import urllib.error
import urllib.request
from dataclasses import dataclass, field
from datetime import date, datetime
from decimal import Decimal, InvalidOperation
from pathlib import Path
from typing import Protocol

# Error classes, kept apart so T19 can report each one separately
# (decisions/2026-10-16-t11-exec-limits-and-scope-message.md). Anything not
# listed here is "engine_error" (the model wrote a query the engine rejected or
# failed on).
SCOPE_VIOLATION = "scope_violation"
FORBIDDEN_STATEMENT = "forbidden_statement"
TIMEOUT = "timeout"
RESOURCE_LIMIT = "resource_limit"       # memory or result-row cap; ``limit`` says which
ENGINE_ERROR = "engine_error"
INTERFACE_LIMITATION = "interface_limitation"
TRANSPORT_ERROR = "transport_error"
INVALID_RESPONSE = "invalid_response"

# Global resource caps: generous but bounded, one value for every question and
# cell (never per question). The largest reference result has 561,293 rows; the
# heaviest reference query (Q33) peaks at about 2.7 GB resident.
DEFAULT_MAX_RESULT_ROWS = 2_000_000
DEFAULT_MAX_MEMORY_BYTES = 16 * 1024**3

# What the model is told when a query reaches outside its cell. Generated by the
# harness: the engine's own message is not passed on, because its "Maybe you
# meant retail.X?" hint would steer the model to a table it cannot use and waste
# the only fix. The engine message / offending names go to runs-raw only.
SCOPE_MESSAGE = "该查询引用了本单元不可用的库或表；本单元可用的数据集见上下文。"
# Table functions that only generate values. Anything else (file, url, s3,
# remote, merge, mysql, ...) reaches outside the cell and is rejected.
ALLOWED_TABLE_FUNCTIONS = frozenset({"numbers", "numbers_mt", "zeros", "zeros_mt", "generateSeries", "generate_series", "values"})
# Session settings the harness pins; a query may not override them.
_PINNED_SETTING = re.compile(r"\b(max_execution_time\w*|timeout_\w+|max_result_\w+|result_overflow_mode|readonly|output_format_\w+|max_estimated_execution_time|max_memory_usage\w*|max_server_memory\w*|memory_overcommit\w*|max_guaranteed_memory\w*)\s*=", re.IGNORECASE)


@dataclass(frozen=True)
class ExecResult:
    """Outcome of one execution. Exactly one of ``rows`` / ``error`` is set."""

    rows: list[list[object]] | None = None
    columns: list[dict[str, str]] = field(default_factory=list)
    error: str | None = None            # the message sent back to the model
    error_class: str | None = None
    elapsed_s: float = 0.0
    detail: str | None = None           # diagnostics kept out of the fix message (runs-raw only)
    limit: str | None = None            # for resource_limit: "memory" or "result_rows"

    @property
    def ok(self) -> bool:
        return self.error is None

    def summary(self, max_error: int = 500) -> dict[str, object]:
        """Log-safe summary: shape, types and a hash — never the rows themselves."""
        if self.ok:
            payload = json.dumps(self.rows, ensure_ascii=False, separators=(",", ":"), default=str)
            return {
                "status": "ok",
                "row_count": len(self.rows or []),
                "columns": self.columns,
                "result_sha256": hashlib.sha256(payload.encode()).hexdigest(),
                "elapsed_s": round(self.elapsed_s, 3),
            }
        out = {
            "status": "error",
            "error_class": self.error_class,
            "error": (self.error or "")[:max_error],
            "elapsed_s": round(self.elapsed_s, 3),
        }
        if self.limit:
            out["limit"] = self.limit
        return out


class Executor(Protocol):
    name: str

    def execute(self, query: str) -> ExecResult: ...


