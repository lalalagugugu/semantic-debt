def test_l1_onto_rebuilds_l1_without_any_entry(source, l1_text):
    ctx, data, _ = source
    p = L.check(ctx, None, l1_text)
    assert L.decode_l1(p, L.Names(ctx, {})) == ctx
    ids = [item["id"] for s in SECTIONS for item in data[s]]
    assert not any(re_search(rf"(?<![A-Za-z0-9]){i}(?![A-Za-z0-9])", l1_text) for i in ids)
    assert not p.typed(":Hierarchy") and ":L1plus" not in p.props
    with pytest.raises(ValueError):    # an L1+ trace in the L1-only text is rejected
        L.check(ctx, None, l1_text.replace('rdfs:label "线上销售明细"', 'rdfs:label "线上销售明细 A01"'))


def re_search(pattern, text):
    import re

    return re.search(pattern, text)


def test_l1_onto_is_a_subgraph_and_the_difference_is_the_entries(source, l1_text):
    ctx, data, full = source
    sub = L.check_subgraph(ctx, data, l1_text, full)
    assert full.startswith(l1_text)          # the L1 part is also byte-identical as text
    ids = {item["id"] for s in SECTIONS for item in data[s]}
    assert set(sub["per_entry"]) == ids | {L.L1PLUS_HEADER}
    assert all(sub["per_entry"][i] > 0 for i in ids)
    assert sub["full"] - sub["l1"] == sum(sub["per_entry"].values())
    # Dropping one triple generated by an entry breaks the accounting.
    broken = full.replace(' ;\n    :exceptionScope class:实体店', '', 1)
    assert broken != full
    with pytest.raises(ValueError):
        L.check_subgraph(ctx, data, l1_text, broken)


